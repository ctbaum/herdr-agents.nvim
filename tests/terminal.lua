local source = debug.getinfo(1, "S").source:sub(2)
local root = vim.fn.fnamemodify(source, ":p:h:h")
vim.opt.runtimepath:prepend(root)
local provider = require("herdr-agents.terminal").provider()
assert(not provider.paste("not running"))
local original = vim.api.nvim_get_current_win()
assert(provider.open("sh -c 'cat'", {}, nil, false))
assert(vim.api.nvim_get_current_win() == original)
local buffer = provider.pane()
assert(buffer and vim.bo[buffer].buftype == "terminal")
provider.focus()
assert(vim.api.nvim_get_current_buf() == buffer)
vim.cmd("stopinsert")
assert(provider.submit("test message", { focus = false }))
local first_window = vim.api.nvim_get_current_win()
local windows = #vim.api.nvim_list_wins()
vim.fn.jobstop(vim.bo[buffer].channel)
assert(vim.wait(1000, function() return provider.pane() == nil end))
assert(provider.open("sh -c 'cat'", {}, nil, false))
assert(#vim.api.nvim_list_wins() == windows)
assert(not vim.api.nvim_win_is_valid(first_window) and not vim.api.nvim_buf_is_valid(buffer))
buffer = provider.pane()
local replacement_window = vim.fn.win_findbuf(buffer)[1]
local unrelated = vim.api.nvim_create_buf(false, false)
vim.api.nvim_buf_set_lines(unrelated, 0, -1, false, { "unsaved work" })
vim.bo[unrelated].bufhidden = "wipe"
vim.bo[unrelated].modified = true
vim.api.nvim_win_set_buf(replacement_window, unrelated)
vim.fn.jobstop(vim.bo[buffer].channel)
assert(vim.wait(1000, function() return provider.pane() == nil end))
assert(provider.open("sh -c 'cat'", {}, nil, false))
assert(vim.api.nvim_win_is_valid(replacement_window))
assert(vim.api.nvim_win_get_buf(replacement_window) == unrelated)
assert(vim.api.nvim_buf_is_valid(unrelated) and vim.bo[unrelated].modified)
buffer = provider.pane()
local final_window = vim.fn.win_findbuf(buffer)[1]
provider.close()
assert(not provider.pane())
assert(not vim.api.nvim_win_is_valid(final_window))
assert(not vim.api.nvim_buf_is_valid(buffer))
assert(vim.api.nvim_buf_is_valid(unrelated))
print("herdr-agents terminal test passed")
vim.cmd("qa!")
